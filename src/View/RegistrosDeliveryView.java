    private void jComboBoxTypeOfDeliveryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxTypeOfDeliveryActionPerformed
        String selectedItem = jComboBoxTypeOfDelivery.getSelectedItem().toString();
        if(selectedItem.equalsIgnoreCase("Bike Delivery") || selectedItem.equalsIgnoreCase("Van Delivery")){
            jLabelDistaneKm.setVisible(true);
            jTextFieldDistanceKm.setVisible(true);
            jButtonClear.setVisible(true);
            jButtonNewDelivery.setVisible(true);
            jLabelChargePerItem.setVisible(false);
            jLabelItems.setVisible(false);
            jTextFieldChargePerItem.setVisible(false);
            jTextFieldItems.setVisible(false);
            
        }else if(selectedItem.equalsIgnoreCase("Packaging")){
            jLabelChargePerItem.setVisible(true);
            jLabelItems.setVisible(true);
            jTextFieldChargePerItem.setVisible(true);
            jTextFieldItems.setVisible(true);
            jButtonClear.setVisible(true);
            jButtonNewDelivery.setVisible(true);
            jLabelDistaneKm.setVisible(false);
            jTextFieldDistanceKm.setVisible(false);
        }
    }//GEN-LAST:event_jComboBoxTypeOfDeliveryActionPerformed

    private void jButtonNewDeliveryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonNewDeliveryActionPerformed
       try{
        //int chargePerItem = Integer.parseInt(jTextFieldChargePerItem.getText());
        //int items = Integer.parseInt(jTextFieldItems.getText());
        //int distanceKm = Integer.parseInt(jTextFieldDistanceKm.getText());
        
        String selectedComboBoxItem = jComboBoxTypeOfDelivery.getSelectedItem().toString();
        
        if(selectedComboBoxItem.equalsIgnoreCase("Bike Delivery")){
            int distanceKm = Integer.parseInt(jTextFieldDistanceKm.getText());
            //BikeDeliveryController b = new BikeDeliveryController();
            trackingId++;
            String newTrackingId = "";
            newTrackingId += trackingId;
            b.registrarBikeDelivery(newTrackingId, distanceKm); 
            JOptionPane.showMessageDialog(null, b.calcularTotalGeneral());
        }else if(selectedComboBoxItem.equalsIgnoreCase("Van Delivery")){
            int distanceKm = Integer.parseInt(jTextFieldDistanceKm.getText());
            //VanDeliveryController b = new VanDeliveryController();
            trackingId++;
            String newTrackingId = "";
            newTrackingId += trackingId;
            v.registrarVanDelivery(newTrackingId, distanceKm);
            JOptionPane.showMessageDialog(null, v.calcularTotalGeneral());
        }else if (selectedComboBoxItem.equalsIgnoreCase("Packaging")) {
               int chargePerItem = Integer.parseInt(jTextFieldChargePerItem.getText());
               int items = Integer.parseInt(jTextFieldItems.getText());
               //PackagingController p = new PackagingController();
               p.registrarPackaging(items, chargePerItem);
               JOptionPane.showMessageDialog(null, p.calcularTotalGeneral());
           }
        
       }catch(NumberFormatException e){
           JOptionPane.showMessageDialog(null, "Error al ingresar los datos");
       }
    }//GEN-LAST:event_jButtonNewDeliveryActionPerformed

    private void jButtonClearActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonClearActionPerformed
        String selectedComboBoxItem = jComboBoxTypeOfDelivery.getSelectedItem().toString();
        if(selectedComboBoxItem.equalsIgnoreCase("Bike Delivery") || selectedComboBoxItem.equalsIgnoreCase("Van Delivery")){
            jTextFieldDistanceKm.setText("");
        }else{
            jTextFieldItems.setText("");
            jTextFieldChargePerItem.setText("");
        }
    }//GEN-LAST:event_jButtonClearActionPerformed

